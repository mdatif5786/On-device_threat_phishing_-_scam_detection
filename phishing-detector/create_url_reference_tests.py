import json
import math
import ipaddress
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent
MODEL_FILE = ROOT / "artifacts" / "url_model.json"
TEST_FILE = ROOT / "artifacts" / "url_reference_tests.json"

SUSPICIOUS = [
    "login", "verify", "update", "secure", "account",
    "signin", "banking", "password", "confirm", "wallet",
    "free", "bonus", "gift", "urgent", "recover",
]


def get_host(url):
    url = str(url).strip()
    if not url:
        return "", None
    if "://" not in url:
        url = "http://" + url
    try:
        parsed = urlsplit(url)
        return (parsed.hostname or "").lower().rstrip("."), parsed
    except ValueError:
        return "", None


def entropy(text):
    if not text:
        return 0.0
    counts = Counter(text)
    n = len(text)
    return -sum((count / n) * math.log2(count / n) for count in counts.values())


def extract_features(url):
    url = str(url).strip()
    host, parsed = get_host(url)
    if not host or parsed is None:
        raise ValueError(f"Invalid URL for reference test: {url}")

    try:
        ipaddress.ip_address(host)
        has_ip = 1.0
    except ValueError:
        has_ip = 0.0

    try:
        port = parsed.port
    except ValueError:
        raise ValueError(f"Invalid port in reference test URL: {url}")

    path = parsed.path or ""
    query = parsed.query or ""
    lower_url = url.lower()
    host_parts = host.split(".")
    digit_count = sum(ch.isdigit() for ch in url)

    return [
        len(url), len(host), len(path), len(query),
        url.count("."), url.count("-"), url.count("@"),
        digit_count / max(len(url), 1),
        max(len(host_parts) - 2, 0),
        1.0 if parsed.scheme.lower() == "https" else 0.0,
        has_ip, 1.0 if port is not None else 0.0,
        url.count("%"), 1.0 if "//" in path else 0.0,
        sum(token in lower_url for token in SUSPICIOUS),
        1.0 if any(word in host for word in
                   ["login", "verify", "secure", "account", "bank"]) else 0.0,
        entropy(host),
        len([part for part in path.split("/") if part]),
    ]


def main():
    if not MODEL_FILE.exists():
        raise FileNotFoundError(f"Model not found: {MODEL_FILE}")

    model = json.loads(MODEL_FILE.read_text(encoding="utf-8"))
    urls = [
        "https://www.google.com/",
        "https://www.wikipedia.org/",
        "https://example.com/",
        "http://example.com/login",
        "https://secure-account.example.com/verify",
        "http://192.0.2.10/login?account=123",
        "https://example.com/free-gift",
        "https://accounts.example.org/signin?confirm=1",
    ]

    tests = []
    for url in urls:
        features = extract_features(url)
        scaled = [
            (float(value) - float(mean)) / float(scale)
            if float(scale) != 0 else 0.0
            for value, mean, scale in zip(
                features, model["scaler_mean"], model["scaler_scale"]
            )
        ]
        score = float(model["intercept"]) + sum(
            float(coef) * value
            for coef, value in zip(model["coefficients"], scaled)
        )
        threshold = float(model.get("threshold", 0.0))
        predicted_label = "phishing" if score >= threshold else "not phishing"

        tests.append({
            "url": url,
            "features": features,
            "score": score,
            "threshold": threshold,
            "predicted_label": predicted_label,
        })

    payload = {
        "format_version": 1,
        "description": (
            "Reference cases generated by Python. Kotlin should reproduce "
            "the feature vector, score, and label for each URL. These are "
            "implementation checks, not a security evaluation."
        ),
        "feature_names": model["feature_names"],
        "score_definition": (
            "score = intercept + sum(coefficient[i] * "
            "((feature[i] - scaler_mean[i]) / scaler_scale[i])); "
            "label phishing when score >= threshold."
        ),
        "tests": tests,
    }

    TEST_FILE.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print("Saved reference tests:", TEST_FILE)
    print("Test cases:", len(tests))
    for test in tests:
        print(f'{test["predicted_label"]:12} score={test["score"]:.6f}  {test["url"]}')


if __name__ == "__main__":
    main()
